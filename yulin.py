# 三张表都按归一后的线名索引：「北流105路」和「北流105」得是同一个键
_WAYS = {key(k): v for k, v in WAYS.items()}
_NOTES = {key(k): v for k, v in NOTES.items()}
_NO_REAL = {key(k): v for k, v in NO_REAL.items()}


_NAME = {k: k for k in _WAYS}        # 打印用平台线名（「G01路」不是「G01」）
for _k, _raw in WAYS.items():
    _NAME[key(_k)] = _k


def ways(line):
    """(线名, {换乘站: 线串}) —— 认不出返回 None。"""
    k = key(line)
    return (_NAME[k], _WAYS[k]) if k in _WAYS else None


def note(line):
    return _NOTES.get(key(line), "")


def no_real(line):
    return _NO_REAL.get(key(line), "")


def split(seq):
    """「1/3/26/G02夜班车」→ ["1", "3", "26", "G02夜班车"]"""
    return [x for x in (seq or "").split("/") if x]


def plan(lines_a, lines_b):
    """两站没有直达：找 A 侧某条线和 B 侧某条线共用的换乘站。返回 (A线, 换乘站, B线) 或 None。"""
    la = {key(x): x for x in lines_a}
    lb = {key(x): x for x in lines_b}
    for name, stops in _WAYS.items():
        if name not in la:
            continue
        for st, s in stops.items():
            for x in split(s):
                if key(x) in lb:
                    return la[name], st, lb[key(x)]
    return None
